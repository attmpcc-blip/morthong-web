// Helper to determine Thai Element from birth date
export function calculateThaiElementFromBirthDate(birthDateStr?: string): ThaiElement {
  if (!birthDateStr) return 'earth';
  const month = parseInt(birthDateStr.split('-')[1], 10);
  if (month >= 10 && month <= 12) return 'earth'; // ต.ค. - ธ.ค.
  if (month >= 1 && month <= 3) return 'fire';   // ม.ค. - มี.ค.
  if (month >= 4 && month <= 6) return 'wind';   // เม.ย. - มิ.ย.
  if (month >= 7 && month <= 9) return 'water';  // ก.ค. - ก.ย.
  return 'earth';
}

